const now = new Date();
const minutesAgo = (m: number) => new Date(now.getTime() - m * 60_000).toISOString();
const daysAgo = (d: number) => minutesAgo(d * 24 * 60);

/** A date in the current month (or the next, for `monthOffset: 1`) at a local time. */
function at(day: number, hour: number, minute = 0, monthOffset = 0) {
  return new Date(now.getFullYear(), now.getMonth() + monthOffset, day, hour, minute).toISOString();
}

