-- Blight reports, their photos (Storage bucket `blight-photos`) and the public read surface.
--
-- Privacy rule: the public must never see reporter_id, keep_name_private or resolution_note.
-- The base table is readable only by the reporter and admins; everyone else reads the
-- `public_blight_reports` view (active reports, safe columns only).

create type public.blight_category as enum (
  'illegal_dumping', 'vacant_lot', 'abandoned_building', 'standing_water', 'air_odor', 'other'
);
create type public.blight_status as enum (
  'submitted', 'under_review', 'reported_to_city', 'resolved', 'removed'
);

create table public.blight_reports (
  -- Shown to residents as "Report #N".
  id bigint generated by default as identity (start with 1001) primary key,
  -- Forced to the caller for client inserts (default + column privileges + RLS check).
  -- ON DELETE SET NULL: deleting an account anonymizes its reports (Q-003 default).
  reporter_id uuid default auth.uid() references public.profiles (id) on delete set null,
  category public.blight_category not null,
  description text check (description is null or char_length(description) <= 2000),
  -- District 3 bounding box (backend DISTRICT_BBOX default).
  latitude numeric(9, 6) not null check (latitude between 33.73 and 33.81),
  longitude numeric(9, 6) not null check (longitude between -84.49 and -84.37),
  address text check (address is null or char_length(address) <= 300),
  keep_name_private boolean not null default true,
  status public.blight_status not null default 'submitted',
  -- [{ "status": "...", "at": "ISO" }], maintained by triggers.
  status_history jsonb not null default '[]'::jsonb check (jsonb_typeof(status_history) = 'array'),
  resolution_note text check (resolution_note is null or char_length(resolution_note) <= 2000),
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.blight_reports is
  'Base table: reporter and admins only. Public reads go through public_blight_reports. Never deleted; status removed is the soft delete.';

create index blight_reports_reporter_idx on public.blight_reports (reporter_id, created_at desc);
create index blight_reports_status_created_idx on public.blight_reports (status, created_at desc);
create index blight_reports_category_created_idx on public.blight_reports (category, created_at desc);

create table public.blight_report_photos (
  id bigint generated always as identity primary key,
  report_id bigint not null references public.blight_reports (id) on delete cascade,
  -- Object name inside the blight-photos bucket: "{report_id}/{file}.jpg|png|webp".
  storage_path text not null unique
    check (storage_path ~* '^[0-9]{1,18}/[A-Za-z0-9._-]{1,128}\.(jpe?g|png|webp)$'),
  created_at timestamptz not null default now(),
  constraint blight_report_photos_path_matches_report check (split_part(storage_path, '/', 1) = report_id::text)
);
create index blight_report_photos_report_idx on public.blight_report_photos (report_id, id);

-- ---------------------------------------------------------------------------------------------
-- Server-maintained fields
-- ---------------------------------------------------------------------------------------------
create function public.blight_reports_before_insert()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user in ('anon', 'authenticated') then
    -- Column privileges already prevent clients from supplying these; belt and braces.
    new.reporter_id := auth.uid();
    new.status := 'submitted';
    new.resolution_note := null;
    new.resolved_at := null;
    new.status_history := '[]'::jsonb;
    new.created_at := now();
  end if;
  new.description := public.clean_text(new.description);
  new.address := public.clean_text(new.address);
  if new.status_history = '[]'::jsonb then
    new.status_history := jsonb_build_array(
      jsonb_build_object('status', new.status, 'at', public.iso_utc(new.created_at)));
  end if;
  if new.status = 'resolved' and new.resolved_at is null then
    new.resolved_at := now();
  end if;
  new.updated_at := now();
  return new;
end
$$;

create trigger blight_reports_before_insert
  before insert on public.blight_reports
  for each row execute function public.blight_reports_before_insert();

create function public.blight_reports_before_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user in ('anon', 'authenticated') then
    new.id := old.id;
    new.reporter_id := old.reporter_id;
    new.created_at := old.created_at;
    new.status_history := old.status_history;
    new.resolved_at := old.resolved_at;
  end if;
  if new.status is distinct from old.status then
    new.status_history := coalesce(old.status_history, '[]'::jsonb)
      || jsonb_build_array(jsonb_build_object('status', new.status, 'at', public.iso_utc(now())));
    if new.status = 'resolved' then
      new.resolved_at := now();
    end if;
  end if;
  if new.description is distinct from old.description then
    new.description := public.clean_text(new.description);
  end if;
  if new.address is distinct from old.address then
    new.address := public.clean_text(new.address);
  end if;
  if new.resolution_note is distinct from old.resolution_note then
    new.resolution_note := public.clean_text(new.resolution_note);
  end if;
  new.updated_at := now();
  return new;
end
$$;

create trigger blight_reports_before_update
  before update on public.blight_reports
  for each row execute function public.blight_reports_before_update();

-- Audit: status change / removal / edit.
create function public.blight_reports_audit()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
declare
  v_changes jsonb;
begin
  select coalesce(jsonb_object_agg(o.key, jsonb_build_object('from', o.value, 'to', n.value)), '{}'::jsonb)
    into v_changes
  from jsonb_each(to_jsonb(old)) o
  join jsonb_each(to_jsonb(new)) n using (key)
  where o.value is distinct from n.value
    and o.key not in ('updated_at', 'status_history', 'resolved_at', 'reporter_id');

  if v_changes = '{}'::jsonb then
    return null; -- e.g. reporter anonymized by account deletion: nothing an admin did
  end if;

  perform public.log_admin_action(
    case
      when new.status is distinct from old.status and new.status = 'removed' then 'report_removed'
      when new.status is distinct from old.status then 'report_status_changed'
      else 'report_edited'
    end::public.admin_action,
    'blight_report', new.id::text,
    jsonb_build_object('changes', v_changes));
  return null;
end
$$;

create trigger blight_reports_audit
  after update on public.blight_reports
  for each row execute function public.blight_reports_audit();

-- Max 5 photos per report (the app enforces min 1 before it shows the report as sent).
-- SECURITY DEFINER so it can lock the report row regardless of the caller's RLS.
create function public.blight_report_photos_limit()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  -- BEFORE triggers run ahead of RLS: leave signed-in non-owners to the RLS check (and its
  -- 42501). (current_user is the definer here, so test the session's uid instead.)
  if auth.uid() is not null and not exists (
    select 1 from public.blight_reports where id = new.report_id and reporter_id = auth.uid()
  ) then
    return new;
  end if;
  perform 1 from public.blight_reports where id = new.report_id for update;
  if (select count(*) from public.blight_report_photos where report_id = new.report_id) >= 5 then
    raise exception 'A report can have at most 5 photos' using errcode = 'P0001';
  end if;
  return new;
end
$$;

create trigger blight_report_photos_limit
  before insert on public.blight_report_photos
  for each row execute function public.blight_report_photos_limit();

-- ---------------------------------------------------------------------------------------------
-- Upload / attach checks (used by RLS policies on storage.objects and blight_report_photos)
-- ---------------------------------------------------------------------------------------------

-- The caller may upload "{report_id}/{file}" when they are an active user, own the report, the
-- report is still `submitted` and less than 24 h old, and it has fewer than 5 objects so far.
-- The path deliberately does NOT contain the reporter's user id: the bucket is public, and a
-- uid in public URLs would link reports to (and between) reporters.
create function public.can_upload_blight_photo(p_name text)
returns boolean
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_report_id bigint;
begin
  if p_name is null or p_name !~* '^[0-9]{1,18}/[A-Za-z0-9._-]{1,128}\.(jpe?g|png|webp)$' then
    return false;
  end if;
  if not public.is_active_user() then
    return false;
  end if;
  v_report_id := split_part(p_name, '/', 1)::bigint;
  if not exists (
    select 1 from public.blight_reports r
    where r.id = v_report_id
      and r.reporter_id = auth.uid()
      and r.status = 'submitted'
      and r.created_at > now() - interval '24 hours'
  ) then
    return false;
  end if;
  return (
    select count(*) from storage.objects o
    where o.bucket_id = 'blight-photos' and o.name like v_report_id::text || '/%'
  ) < 5;
end
$$;

-- Reporter (or admin) may see/list the objects of their report through the Storage API.
-- Public URLs work for everyone anyway (public bucket); this only governs the API.
create function public.can_read_blight_photo_object(p_name text)
returns boolean
language plpgsql stable security definer
set search_path = ''
as $$
begin
  if public.is_admin() then
    return true;
  end if;
  if p_name is null or p_name !~ '^[0-9]{1,18}/' then
    return false;
  end if;
  return exists (
    select 1 from public.blight_reports r
    where r.id = split_part(p_name, '/', 1)::bigint and r.reporter_id = auth.uid()
  );
end
$$;

-- A photo row may be attached by the reporter, under the same conditions as the upload, and
-- only once the object really exists in the bucket.
create function public.can_attach_blight_photo(p_report_id bigint, p_storage_path text)
returns boolean
language plpgsql stable security definer
set search_path = ''
as $$
begin
  return public.is_active_user()
    and split_part(p_storage_path, '/', 1) = p_report_id::text
    and exists (
      select 1 from public.blight_reports r
      where r.id = p_report_id
        and r.reporter_id = auth.uid()
        and r.status = 'submitted'
        and r.created_at > now() - interval '24 hours'
    )
    and exists (
      select 1 from storage.objects o
      where o.bucket_id = 'blight-photos' and o.name = p_storage_path
    );
end
$$;

