-- Runs with the view owner's rights (security_invoker off, the default) so it can read the
-- base table past its RLS; security_barrier stops caller-supplied filters from being evaluated
-- before the view's own WHERE clause.
create view public.public_blight_reports
with (security_barrier = true)
as
select
  r.id,
  r.category,
  r.description,
  r.latitude,
  r.longitude,
  r.address,
  r.status,
  r.status_history,
  coalesce(
    (select array_agg(p.storage_path order by p.id) from public.blight_report_photos p where p.report_id = r.id),
    '{}'::text[]
  ) as photo_paths,
  r.resolved_at,
  r.created_at,
  r.updated_at
from public.blight_reports r
where r.status in ('submitted', 'under_review', 'reported_to_city');
comment on view public.public_blight_reports is
  'Active blight reports for everyone (guests included). No reporter, keep_name_private or resolution_note. photo_paths are object names in the public blight-photos bucket.';

-- Active reports near a point, sorted by distance (backend `near=lat,lng&radiusKm`).
create function public.public_blight_reports_near(
  p_lat double precision,
  p_lng double precision,
  p_radius_km double precision default 2
)
returns table (
  id bigint,
  category public.blight_category,
  description text,
  latitude numeric,
  longitude numeric,
  address text,
  status public.blight_status,
  status_history jsonb,
  photo_paths text[],
  resolved_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  distance_km double precision
)
language plpgsql stable
set search_path = ''
as $$
begin
  if p_lat is null or p_lng is null or abs(p_lat) > 90 or abs(p_lng) > 180 then
    raise exception 'p_lat/p_lng must be valid coordinates' using errcode = '22023';
  end if;
  if p_radius_km is null or p_radius_km <= 0 or p_radius_km > 50 then
    raise exception 'p_radius_km must be between 0 and 50' using errcode = '22023';
  end if;
  return query
  select v.id, v.category, v.description, v.latitude, v.longitude, v.address, v.status,
         v.status_history, v.photo_paths, v.resolved_at, v.created_at, v.updated_at, d.km
  from public.public_blight_reports v
  cross join lateral (
    select public.haversine_km(p_lat, p_lng, v.latitude::double precision, v.longitude::double precision) as km
  ) d
  where d.km <= p_radius_km
  order by d.km, v.id;
end
$$;

-- Duplicate check (Q-013 default): same category within 50 m in the last 30 days. Only active
-- reports (the same set the public can already see), and only id/status/created_at.
create function public.nearby_blight_reports(
  p_category public.blight_category,
  p_lat double precision,
  p_lng double precision
)
returns table (id bigint, status public.blight_status, created_at timestamptz)
language sql stable
set search_path = ''
as $$
  select v.id, v.status, v.created_at
  from public.public_blight_reports v
  where v.category = p_category
    and v.created_at > now() - interval '30 days'
    and public.haversine_km(p_lat, p_lng, v.latitude::double precision, v.longitude::double precision) <= 0.05
  order by v.created_at desc
$$;

