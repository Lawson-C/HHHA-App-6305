alter table public.blight_reports enable row level security;
alter table public.blight_report_photos enable row level security;

revoke all on table public.blight_reports from anon, authenticated;
revoke all on table public.blight_report_photos from anon, authenticated;
revoke all on table public.public_blight_reports from anon, authenticated;
grant all on table public.blight_reports, public.blight_report_photos to service_role;
grant select on table public.public_blight_reports to anon, authenticated, service_role;

-- Reporter (active account) and admins.
create policy blight_reports_select on public.blight_reports
  for select to authenticated
  using ((reporter_id = (select auth.uid()) and (select public.is_active_user())) or (select public.is_admin()));

create policy blight_reports_insert on public.blight_reports
  for insert to authenticated
  with check (reporter_id = (select auth.uid()) and status = 'submitted' and (select public.is_active_user()));

-- Admin moderation. Reporters can't edit their own report (backend parity).
create policy blight_reports_update on public.blight_reports
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));
-- No DELETE policy or privilege: status 'removed' is the soft delete.

grant select on table public.blight_reports to authenticated;
grant insert (category, description, latitude, longitude, address, keep_name_private)
  on table public.blight_reports to authenticated;
grant update (category, description, latitude, longitude, address, keep_name_private, status, resolution_note)
  on table public.blight_reports to authenticated;

-- Photo rows: visible with the report (RLS of blight_reports applies inside the subquery).
create policy blight_report_photos_select on public.blight_report_photos
  for select to authenticated
  using (exists (select 1 from public.blight_reports r where r.id = report_id));

create policy blight_report_photos_insert on public.blight_report_photos
  for insert to authenticated
  with check ((select public.can_attach_blight_photo(report_id, storage_path)));

-- Moderators can take down an inappropriate photo.
create policy blight_report_photos_delete on public.blight_report_photos
  for delete to authenticated
  using ((select public.is_admin()));

grant select on table public.blight_report_photos to authenticated;
grant insert (report_id, storage_path) on table public.blight_report_photos to authenticated;
grant delete on table public.blight_report_photos to authenticated;

-- ---------------------------------------------------------------------------------------------
-- Storage: public-read bucket, JPEG/PNG/WebP, 10 MB. (The Storage API enforces size and the
-- declared MIME type; the app must strip EXIF by re-encoding before upload.)
-- ---------------------------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('blight-photos', 'blight-photos', true, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

create policy "blight-photos: reporter uploads"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'blight-photos' and (select public.can_upload_blight_photo(name)));

create policy "blight-photos: reporter and admins read via API"
  on storage.objects for select to authenticated
  using (bucket_id = 'blight-photos' and (select public.can_read_blight_photo_object(name)));

create policy "blight-photos: admins delete"
  on storage.objects for delete to authenticated
  using (bucket_id = 'blight-photos' and (select public.is_admin()));
